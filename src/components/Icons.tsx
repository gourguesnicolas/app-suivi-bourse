export function Arrow({ tone }: { tone: Tone }) {
  if (tone === 'flat') return <span className="arrow arrow-flat" aria-hidden="true">–</span>;
  return (
    <svg className="arrow" viewBox="0 0 10 10" width="10" height="10" aria-hidden="true">
      <path d={tone === 'up' ? 'M5 1.5 9 8.5H1z' : 'M5 8.5 1 1.5h8z'} fill="currentColor" />
    </svg>
  );
}

